// Generated TypeScript DECLARATIONS for a project — a developer/editor artifact, never a source of truth.
//
// This module is pure: same resources in → byte-identical text out. It reads nothing, writes nothing and
// knows nothing about builds. The declarations are a PROJECTION of what the platform already owns — the
// normalized entity fields the entity tools validated, and the backend-function metadata
// describeFunctions() already derives from source — so the file can never disagree with the runtime
// models, and nothing downstream may treat it as authoritative. The generated app stays plain JavaScript:
// buildEngine parses only .js, so a stale or hand-edited declaration file can never fail a build.
//
// The emitted SHAPE follows the Base44 CLI's own `types generate` output (packages/cli/src/core/types/
// generator.ts): the generated-file header, an `import '@base44/sdk';` side-effect import, one exported
// interface per entity carrying ONLY its declared fields (the SDK adds id/created_date/updated_date/
// created_by_id itself through EntityRecord + ServerEntityFields), then a `declare module '@base44/sdk'`
// augmentation block holding presence registries in the CLI's order. Nothing is invented: a function
// contributes its NAME only, because the platform cannot read its payload or response shape. A registry
// with no entries is omitted entirely, so an absent resource kind never narrows the SDK's own fallbacks.

/** Field type → TypeScript type. Exactly the field types the entity tools accept. */
const SCALARS = { string: "string", text: "string", number: "number", boolean: "boolean", date: "string" };

const IDENT_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (name) => (IDENT_RE.test(name) ? name : JSON.stringify(name));
const quote = (v) => JSON.stringify(String(v));

/** The interface name for a resource name. The registry KEY keeps the raw name; only the type is renamed. */
const toPascalCase = (name) =>
  String(name)
    .split(/[-_\s]+/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");

/** The TypeScript type of ONE normalized field. An enum becomes the union of its DECLARED values. */
function fieldType(def) {
  const d = def || {};
  if (d.type === "enum") {
    const values = Array.isArray(d.enum) ? d.enum.filter((v) => v != null) : [];
    return values.length ? values.map(quote).join(" | ") : "string";
  }
  return SCALARS[d.type] || "unknown";
}

/**
 * One entity's interface: its declared fields, in declaration order, and NOTHING else. Platform record
 * attributes are deliberately absent — the SDK's own EntityRecord intersects them in, so emitting them
 * here would duplicate (and could contradict) the SDK's definition.
 */
function entityInterface({ name, fields }) {
  const lines = [`export interface ${toPascalCase(name)} {`];
  for (const [field, def] of Object.entries(fields || {})) {
    const d = def || {};
    if (d.description) lines.push(`  /** ${String(d.description).replace(/\*\//g, "*\\/").replace(/[\r\n]+/g, " ")} */`);
    lines.push(`  ${key(field)}${d.required ? "" : "?"}: ${fieldType(d)};`);
  }
  lines.push("}");
  return lines.join("\n");
}

const HEADER = ["// Auto-generated by Base44 CLI - DO NOT EDIT", "// Regenerate with: base44 types generate"].join("\n");

const SDK_IMPORT = "import '@base44/sdk';";

/** The exact text emitted when a project declares no resources of any kind. */
const EMPTY_TEMPLATE = [
  "// Auto-generated by Base44 CLI - DO NOT EDIT",
  "// Regenerate with: base44 types",
  "//",
  "// No entities, functions, actors, agents, or connectors found in project.",
  "// Add resources to base44/entities/, base44/functions/, base44/actors/, base44/agents/, or base44/connectors/",
  "// and run `base44 types generate` again.",
  "",
  SDK_IMPORT,
  "",
  "declare module '@base44/sdk' {",
  "  // No types to augment - add resources and regenerate",
  "}",
].join("\n");

/** One registry inside the augmentation block. Callers omit it entirely when it has no entries. */
function registry(name, entries) {
  return [`  interface ${name} {`, ...entries.map((e) => `    ${e}`), "  }"].join("\n");
}

const byName = (items) => [...(items || [])].filter((i) => i?.name).sort((a, b) => a.name.localeCompare(b.name));

/**
 * The complete `base44/.types/types.d.ts` text.
 *
 * `entities` are the runtime entity records ({ name, fields }) and `functions` are describeFunctions()
 * output. `actors`, `agents` and `connectors` are accepted so the emitted shape matches the platform
 * contract, and each is empty until NexusAI actually declares that resource kind — an empty registry is
 * omitted rather than emitted. Every collection is sorted, so the output depends only on CONTENT — never
 * on the order the pipeline happened to collect it.
 */
export function generateTypes({ entities = [], functions = [], actors = [], agents = [], connectors = [] } = {}) {
  const ents = byName(entities);
  const fns = byName(functions);
  const acts = byName(actors);
  const agts = byName(agents);
  const conns = [...(connectors || [])].filter((c) => c?.type).sort((a, b) => a.type.localeCompare(b.type));

  if (!ents.length && !fns.length && !acts.length && !agts.length && !conns.length) return `${EMPTY_TEMPLATE}\n`;

  // Registry order is part of the contract: entities, functions, actors, agents, connectors.
  const registries = [
    ["EntityTypeRegistry", ents.map((e) => `${quote(e.name)}: ${toPascalCase(e.name)};`)],
    ["FunctionNameRegistry", fns.map((f) => `${quote(f.name)}: true;`)],
    ["ActorNameRegistry", acts.map((a) => `${quote(a.name)}: true;`)],
    ["AgentNameRegistry", agts.map((a) => `${quote(a.name)}: true;`)],
    ["ConnectorTypeRegistry", conns.map((c) => `${quote(c.type)}: true;`)],
  ]
    .filter(([, entries]) => entries.length > 0)
    .map(([name, entries]) => registry(name, entries));

  const parts = [
    HEADER,
    SDK_IMPORT,
    ents.length ? ents.map(entityInterface).join("\n\n") : null,
    ["declare module '@base44/sdk' {", registries.join("\n\n"), "}"].join("\n"),
  ].filter(Boolean);

  return `${parts.join("\n\n")}\n`;
}